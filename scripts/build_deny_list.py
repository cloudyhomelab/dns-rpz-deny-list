"""Rebuild deny-list.txt from personal-deny-list.txt and the sources in blocklists.json."""

import json
import os
import re
import sys
import tempfile
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = REPO_ROOT / "blocklists.json"
PERSONAL_PATH = REPO_ROOT / "personal-deny-list.txt"
EXCLUDE_PATH = REPO_ROOT / "exclude-list.txt"
OUTPUT_PATH = REPO_ROOT / "deny-list.txt"
PREVIOUS_PATH = REPO_ROOT / "deny-list.txt.previous"

# Seconds to wait for each download.
FETCH_TIMEOUT = 60
# Downloads larger than this abort the run; the biggest loaded RPZ zones are ~10 MB.
MAX_DOWNLOAD_BYTES = 100 * 1024 * 1024
# Rejected names printed per source; the rest are only counted.
REJECT_SAMPLE_SIZE = 5

USER_AGENT = "dns-rpz-deny-list-builder"
OUTPUT_HEADER = [
    "Generated by scripts/build_deny_list.py; edit personal-deny-list.txt or blocklists.json instead.",
    "Entries from the sources below keep their source's license. Changes: converted to one domain per line,",
    "deduplicated, and names already blocked by a loaded RPZ zone or covered by a listed parent domain removed.",
]

# Lowercase, no trailing dot, no "*." prefix; underscores are allowed because RPZ owner names may contain them.
DENY_NAME_PATTERN = re.compile(r"^([a-z0-9_]([a-z0-9_-]*[a-z0-9_])?\.)*[a-z0-9_]([a-z0-9_-]*[a-z0-9_])?$")
MAX_NAME_LENGTH = 253
MAX_LABEL_LENGTH = 63

ADBLOCK_RULE = re.compile(r"^\|\|([^/^$|]+)\^$")
# Only "(\.|^)zone$" and "^host$" mean a fixed name; any other regex cannot be listed as names.
PIHOLE_NAME_RULE = re.compile(r"^(?:\(\\\.\|\^\)|\^)((?:[a-z0-9_-]+\\\.)*[a-z0-9_-]+)\$$")
# RPZ actions that block; rpz-passthru. and local-data answers do not.
RPZ_BLOCK_TARGETS = {".", "*.", "rpz-drop."}
# Lower rank wins when max_entries forces a cut; sources rank 1.. in config order, deny-list.txt.previous after them.
PERSONAL_RANK = 0
ATTRIBUTION_KEYS = ("name", "license", "author", "homepage")

EXIT_CLEAN = 0
EXIT_NOTHING_WRITTEN = 1
# Merged with deny-list.txt.previous because an input failed.
EXIT_WRITTEN_WITH_ERRORS = 2


class BuildError(Exception):
    pass


@dataclass
class SourceReport:
    name: str
    accepted: int = 0
    rejected: list[str] = field(default_factory=list)


def fetch(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=FETCH_TIMEOUT) as response:
            body = response.read(MAX_DOWNLOAD_BYTES + 1)
    except OSError as error:
        raise BuildError(f"fetching {url} failed: {error}") from error
    if len(body) > MAX_DOWNLOAD_BYTES:
        raise BuildError(f"{url} is larger than {MAX_DOWNLOAD_BYTES} bytes")
    return body.decode("utf-8", errors="replace")


def strip_comment(line: str) -> str:
    return line.split("#", 1)[0].strip()


def candidates_domains(text: str) -> list[str]:
    names = []
    for line in text.splitlines():
        content = strip_comment(line)
        if content and not content.startswith("!"):
            names.append(content)
    return names


def candidates_hosts(text: str, ignore: set[str]) -> list[str]:
    names = []
    for line in text.splitlines():
        fields = strip_comment(line).split()
        names.extend(name for name in fields[1:] if name.lower() not in ignore)
    return names


def candidates_adblock(text: str) -> list[str]:
    names = []
    for line in text.splitlines():
        match = ADBLOCK_RULE.match(line.strip())
        if match:
            names.append(match.group(1))
    return names


def candidates_pihole_regex(text: str) -> list[str]:
    """Return the fixed names; other rules are returned as written so validation rejects and reports them."""
    names = []
    for line in text.splitlines():
        rule = line.strip()
        if not rule or rule.startswith("#"):
            continue
        match = PIHOLE_NAME_RULE.match(rule)
        names.append(match.group(1).replace("\\.", ".") if match else rule)
    return names


def normalize(raw: str) -> str | None:
    """Return the name as deny-list.txt stores it, or None if it is not a valid domain."""
    name = raw.strip().lower().rstrip(".").removeprefix("*.").lstrip(".")
    try:
        name = name.encode("idna").decode("ascii")
    except UnicodeError:
        return None
    labels = name.split(".")
    if len(name) > MAX_NAME_LENGTH or any(len(label) > MAX_LABEL_LENGTH for label in labels):
        return None
    # Single labels would block a whole TLD; an all-digit last label is an IP address, not a domain.
    if len(labels) < 2 or labels[-1].isdigit():
        return None
    if not DENY_NAME_PATTERN.match(name):
        return None
    return name


def collect(name: str, candidates: list[str]) -> tuple[set[str], SourceReport]:
    report = SourceReport(name)
    domains = set()
    for candidate in candidates:
        domain = normalize(candidate)
        if domain is None:
            report.rejected.append(candidate)
        else:
            domains.add(domain)
            report.accepted += 1
    return domains, report


def parse_rpz(text: str) -> tuple[set[str], set[str]]:
    """Return (exact, wildcard) owner names that the zone blocks; wildcard holds X for each *.X record."""
    exact, wildcard = set(), set()
    for line in text.splitlines():
        if not line or line[0] in ";$@ \t":
            continue
        fields = line.split(";", 1)[0].split()
        if "CNAME" not in fields:
            continue
        target_index = fields.index("CNAME") + 1
        owner = fields[0].lower()
        # Absolute owners carry the zone origin, which the file does not reliably state; relative names are the norm.
        if target_index >= len(fields) or fields[target_index] not in RPZ_BLOCK_TARGETS or owner.endswith("."):
            continue
        if owner.startswith("*."):
            wildcard.add(owner[2:])
        else:
            exact.add(owner)
    return exact, wildcard


def strict_ancestors(domain: str) -> list[str]:
    labels = domain.split(".")
    return [".".join(labels[i:]) for i in range(1, len(labels))]


def is_covered(domain: str, exact: set[str], wildcard: set[str]) -> bool:
    """True if the loaded zones already block the domain and all its subdomains, as our entry would."""
    if any(ancestor in wildcard for ancestor in strict_ancestors(domain)):
        return True
    return domain in exact and domain in wildcard


def collapse(domains: set[str]) -> set[str]:
    """Drop names whose parent is also listed; every entry already stands for its subdomains."""
    return {domain for domain in domains if not any(a in domains for a in strict_ancestors(domain))}


def missing_attribution(entry: dict) -> list[str]:
    return [key for key in ATTRIBUTION_KEYS if not entry.get(key)]


def credit(label: str, entry: dict) -> str:
    return f"{label}: {entry['name']} by {entry['author']}, {entry['license']}, {entry['homepage']}"


def attribution(config: dict) -> list[str]:
    """Credit every source and loaded zone the list is built from; incomplete ones were skipped and are left out."""
    sources = [credit("Source", source) for source in config.get("sources", []) if not missing_attribution(source)]
    zones = [
        credit("Filtered against", zone) for zone in config.get("loaded_rpz_zones", []) if not missing_attribution(zone)
    ]
    return sources + zones


def write_atomically(path: Path, header: list[str], lines: list[str]) -> None:
    descriptor, temp_name = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.writelines(f"# {line}\n" if line else "#\n" for line in header)
            handle.writelines(f"{line}\n" for line in lines)
        os.replace(temp_name, path)
    except BaseException:
        os.unlink(temp_name)
        raise


def candidates_for(source: dict, hosts_ignore: set[str]) -> list[str]:
    text = fetch(source["url"])
    source_format = source["format"]
    if source_format == "domains":
        return candidates_domains(text)
    if source_format == "hosts":
        return candidates_hosts(text, hosts_ignore)
    if source_format == "adblock":
        return candidates_adblock(text)
    if source_format == "pihole-regex":
        return candidates_pihole_regex(text)
    raise BuildError(f"unknown format {source_format!r}")


def read_excludes(problems: list[str]) -> set[str]:
    try:
        exclude_text = EXCLUDE_PATH.read_text(encoding="utf-8")
    except FileNotFoundError:
        return set()
    except OSError as error:
        problems.append(f"{EXCLUDE_PATH.name} skipped: {error}")
        return set()
    exclude_candidates = candidates_domains(exclude_text)
    excludes, report = collect(EXCLUDE_PATH.name, exclude_candidates)
    problems.extend(f"{EXCLUDE_PATH.name} entry {raw!r} skipped: not a valid domain" for raw in report.rejected)
    return excludes


def print_report(report: SourceReport) -> None:
    print(f"source {report.name}: {report.accepted} accepted, {len(report.rejected)} rejected", file=sys.stderr)
    for rejected in report.rejected[:REJECT_SAMPLE_SIZE]:
        print(f"  rejected: {rejected!r}", file=sys.stderr)


def keep_within(final: set[str], rank: dict[str, int], max_entries: int) -> set[str]:
    """Keep the max_entries entries from the earliest inputs; personal entries are always kept, even beyond the cap."""
    # A kept parent inherits the best rank of the names it absorbed, so collapsing never demotes a personal entry.
    effective = {domain: rank[domain] for domain in final}
    for domain, domain_rank in rank.items():
        owner = next((a for a in [domain, *strict_ancestors(domain)] if a in final), None)
        if owner is not None and domain_rank < effective[owner]:
            effective[owner] = domain_rank
    by_priority = sorted(final, key=lambda domain: (effective[domain], domain))
    personal_count = sum(1 for domain_rank in effective.values() if domain_rank == PERSONAL_RANK)
    return set(by_priority[: max(max_entries, personal_count)])


def read_previous() -> set[str]:
    try:
        previous_text = PREVIOUS_PATH.read_text(encoding="utf-8")
    except FileNotFoundError:
        return set()
    previous_candidates = candidates_domains(previous_text)
    previous, _ = collect(PREVIOUS_PATH.name, previous_candidates)
    return previous


def build() -> list[str]:
    """Write deny-list.txt from every input that can be read and return the errors met on the way."""
    problems = []
    config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    hosts_ignore = {name.lower() for name in config.get("hosts_ignore", [])}
    excludes = read_excludes(problems)

    rank: dict[str, int] = {}
    personal: set[str] = set()
    inputs_read = 0
    try:
        personal_text = PERSONAL_PATH.read_text(encoding="utf-8")
        personal_candidates = candidates_domains(personal_text)
        personal, personal_report = collect(PERSONAL_PATH.name, personal_candidates)
        rank.update(dict.fromkeys(personal, PERSONAL_RANK))
        inputs_read += 1
        print_report(personal_report)
    except OSError as error:
        problems.append(f"{PERSONAL_PATH.name} skipped: {error}")

    for index, source in enumerate(config.get("sources", []), start=1):
        name = source.get("name", f"sources[{index - 1}]")
        try:
            # The list is built from this work, so a source that cannot be credited is not used.
            missing = missing_attribution(source)
            if missing:
                raise BuildError(f"missing {', '.join(missing)}")
            candidates = candidates_for(source, hosts_ignore)
            source_domains, report = collect(name, candidates)
        except Exception as error:
            problems.append(f"source {name} skipped: {error!r}")
            continue
        for domain in source_domains:
            rank.setdefault(domain, index)
        inputs_read += 1
        print_report(report)

    if inputs_read == 0:
        raise BuildError("no input could be read; deny-list.txt left unchanged")

    exact, wildcard = set(), set()
    for zone in config.get("loaded_rpz_zones", []):
        name = zone.get("name", zone.get("url"))
        try:
            missing = missing_attribution(zone)
            if missing:
                raise BuildError(f"missing {', '.join(missing)}")
            zone_text = fetch(zone["url"])
            zone_exact, zone_wildcard = parse_rpz(zone_text)
        except Exception as error:
            problems.append(f"loaded zone {name} skipped, its names may be duplicated here: {error!r}")
            continue
        if not zone_exact and not zone_wildcard:
            problems.append(f"loaded zone {name} skipped: no blocking records")
            continue
        exact |= zone_exact
        wildcard |= zone_wildcard
        print(f"loaded zone {name}: {len(zone_exact)} names, {len(zone_wildcard)} wildcards", file=sys.stderr)

    # A failed input would silently shrink the list, so keep the last clean build's entries until a run succeeds.
    if problems:
        previous = read_previous()
        previous_rank = len(config.get("sources", [])) + 1
        for domain in previous:
            rank.setdefault(domain, previous_rank)
        print(f"errors in this run: merged {len(previous)} entries from {PREVIOUS_PATH.name}", file=sys.stderr)

    # Excludes trim what sources and the previous list bring in; personal entries are deliberate and stay.
    merged_count = len(rank)
    for domain in sorted(excludes & personal):
        print(f"exclude entry kept because it is a personal entry: {domain}", file=sys.stderr)
    for domain in sorted(excludes - rank.keys()):
        print(f"exclude entry matched nothing: {domain}", file=sys.stderr)
    excluded = {domain for domain in excludes - personal if domain in rank}
    for domain in excluded:
        del rank[domain]

    covered = {domain for domain in rank if is_covered(domain, exact, wildcard)}
    for domain in sorted(covered & personal):
        print(f"personal entry already blocked by a loaded zone: {domain}", file=sys.stderr)
    for domain in covered:
        del rank[domain]
    collapsed = collapse(set(rank))

    max_entries = config["max_entries"]
    final = keep_within(collapsed, rank, max_entries)
    if len(final) < len(collapsed):
        dropped = len(collapsed) - len(final)
        print(f"warning: {dropped} entries over max_entries {max_entries} dropped, latest sources first", file=sys.stderr)
    # An entry blocks all its subdomains, so excluding a subdomain of a listed or loaded name has no effect.
    for domain in sorted(excludes - personal):
        parent = next((ancestor for ancestor in strict_ancestors(domain) if ancestor in final), None)
        if parent is not None:
            print(f"warning: excluded {domain} is still blocked through listed parent {parent}", file=sys.stderr)
        elif domain in exact or any(ancestor in wildcard for ancestor in strict_ancestors(domain)):
            print(f"warning: excluded {domain} is still blocked by a loaded zone", file=sys.stderr)
    print(
        f"merged {merged_count}, excluded {len(excluded)}, already loaded {len(covered)}, "
        f"collapsed {len(rank) - len(collapsed)}, written {len(final)}",
        file=sys.stderr,
    )
    lines = sorted(final)
    header = [*OUTPUT_HEADER, "", *attribution(config), ""]
    write_atomically(OUTPUT_PATH, header, lines)
    if not problems:
        write_atomically(PREVIOUS_PATH, header, lines)
    return problems


def print_error(message: str) -> None:
    # One line per error, so CI can grep "^error: " from stderr into the job summary.
    print(f"error: {' '.join(message.split())}", file=sys.stderr)


def main() -> int:
    try:
        problems = build()
    except BuildError as error:
        print_error(str(error))
        return EXIT_NOTHING_WRITTEN
    for problem in problems:
        print_error(problem)
    return EXIT_WRITTEN_WITH_ERRORS if problems else EXIT_CLEAN


if __name__ == "__main__":
    sys.exit(main())
